const flagged = (text: string) => detectCrisis(text).isCrisis

describe('detectCrisis golden set', () => {
  it('is large enough and covers English, Hinglish and Devanagari', () => {
    const positives = LANGS.flatMap((l) => POSITIVE[l]).concat(KNOWN_MISSES)
    const negatives = LANGS.flatMap((l) => NEGATIVE[l])
    expect(positives.length).toBeGreaterThanOrEqual(40)
    expect(negatives.length).toBeGreaterThanOrEqual(20)
    for (const lang of LANGS) {
      expect(POSITIVE[lang].length, `${lang} positives`).toBeGreaterThanOrEqual(
        10,
      )
      expect(NEGATIVE[lang].length, `${lang} negatives`).toBeGreaterThanOrEqual(
        5,
      )
    }
    expect(new Set(positives).size).toBe(positives.length)
    expect(new Set(negatives).size).toBe(negatives.length)
  })

  it(`keeps recall >= ${MIN_RECALL} and false-positive rate <= ${MAX_FALSE_POSITIVE_RATE}`, () => {
    const positives = LANGS.flatMap((l) => POSITIVE[l]).concat(KNOWN_MISSES)
    const negatives = LANGS.flatMap((l) => NEGATIVE[l])
    const missed = positives.filter((t) => !flagged(t))
    const falseAlarms = negatives.filter(flagged)
    const recall = 1 - missed.length / positives.length
    const falsePositiveRate = falseAlarms.length / negatives.length

    const perLang = LANGS.map((lang) => {
      const p = POSITIVE[lang]
      const n = NEGATIVE[lang]
      const hit = p.filter(flagged).length
      const fa = n.filter(flagged).length
      return `${lang}: recall ${hit}/${p.length}, false positives ${fa}/${n.length}`
    }).join('; ')
    const unexpectedMisses = missed.filter((t) => !KNOWN_MISSES.includes(t))
    const report = [
      `recall ${recall.toFixed(3)}, FPR ${falsePositiveRate.toFixed(3)} (${perLang})`,
      `missed (excluding KNOWN_MISSES): ${JSON.stringify(unexpectedMisses, null, 1)}`,
      `false alarms: ${JSON.stringify(falseAlarms, null, 1)}`,
    ].join('\n')

    expect(recall, report).toBeGreaterThanOrEqual(MIN_RECALL)
    expect(falsePositiveRate, report).toBeLessThanOrEqual(
      MAX_FALSE_POSITIVE_RATE,
    )
  })
})
